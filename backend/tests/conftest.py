@pytest.fixture(scope="session")
def silent_video() -> bytes:
    """A real 1-second mp4 with no audio track, generated by ffmpeg."""
    if not shutil.which("ffmpeg"):
        pytest.skip("ffmpeg not installed")
    out = _TMP / "silent.mp4"
    subprocess.run(["ffmpeg", "-y", "-loglevel", "error", "-f", "lavfi", "-i",
                    "color=c=black:s=64x64:d=1", "-pix_fmt", "yuv420p", str(out)], check=True)
    return out.read_bytes()


@pytest.fixture(scope="session")
def talking_video() -> bytes:
    """A real 3-second mp4 with colour frames and an audio track, generated by ffmpeg."""
    if not shutil.which("ffmpeg"):
        pytest.skip("ffmpeg not installed")
    out = _TMP / "talking.mp4"
    subprocess.run(["ffmpeg", "-y", "-loglevel", "error",
                    "-f", "lavfi", "-i", "testsrc=size=320x568:rate=10:duration=3",
                    "-f", "lavfi", "-i", "sine=frequency=440:duration=3",
                    "-shortest", "-pix_fmt", "yuv420p", "-c:a", "aac", str(out)], check=True)
    return out.read_bytes()
